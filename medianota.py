nota1 = float(input("Digite a primeira nota: "))        #receber informação digitada
nota2 = float(input("Digite a segunda nota: "))         #receber informação digitada
nota3 = float(input("Digite a terceira nota: "))        #receber informação digitada
#obs: float, então será com casa decimal

media = (nota1 + nota2 + nota3) / 3 #calcular a média

print(f"Média: {media:.2f}") #mostrara o valor da média com duas casas decimais